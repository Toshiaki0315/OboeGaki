// 行頭の記法（リスト・やること・見出し）の正規表現。3 ファイルに 9 定義が散って
// いて、同じ形のものと**意図して違う**ものが見分けられなかった（19-3）。
// 違いは名前で言う — ここにある違いは仕様で、揃えるなら ADR を書く。

/// 点の項目 `- ` `* ` `+ `（字下げは任意）
export const BULLET_ITEM_RE = /^[ \t]*[-*+][ \t]+/;

/// 番号の項目 `1. ` `12) `（番号は 9 桁まで = CommonMark）
export const ORDERED_ITEM_RE = /^[ \t]*\d{1,9}[.)][ \t]+/;

/// 番号の項目を部品に分ける: 字下げ・番号・区切り（`.` か `)`）・後ろの空白。
/// Enter の継続と字下げの振り直し（ADR-0066）が番号を組み替えるのに使う
export const ORDERED_PARTS_RE = /^([ \t]*)(\d{1,9})([.)])([ \t]+)/;

/// 点か番号の項目の頭（印まで）。書式コマンドが印を付け外しするときの単位
export const LIST_HEAD_RE = /^([ \t]*(?:[-*+]|\d{1,9}[.)])[ \t]+)/;

/// やること（点・番号どちらでも）。書式コマンドのチェックボックスの切り替え用。
/// 印の後ろの空白は 1 つ以上
export const LIST_TASK_RE =
  /^([ \t]*(?:[-*+]|\d{1,9}[.)])[ \t]+)\[( |[xX])\][ \t]+/;

/// やること（**点だけ**）。Enter の継続用 — 番号付きのやること `1. [ ]` は番号を
/// 継続するだけで `[ ]` は付けない（17-8 で決めた。番号の道は ORDERED_PARTS_RE）
export const BULLET_TASK_RE = /^([ \t]*[-*+][ \t]+)\[[ xX]\]([ \t]+)/;

/// やることの行（一覧と完了の切り替え。Rust `tasks::task_marker` と同じ規則）。
/// **印の前後は空白ちょうど 1 つ**、後ろは空白か行末。共有の見本
/// fixtures/task-marker-cases.json が両側を見張る（`- [ ]a` は印でない）
export const TASK_LINE_RE =
  /^([ \t]*(?:[-*+]|\d{1,9}[.)]) )\[( |x|X)\](?:( )(.*)|$)/;

/// ATX 見出し `# 題`（3 字までの字下げを許す = CommonMark）
export const ATX_HEADING_RE = /^( {0,3})(#{1,6})[ \t]+/;
